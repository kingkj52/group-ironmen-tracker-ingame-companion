package com.groupironmencompanion.map;

import com.google.gson.Gson;
import com.google.gson.JsonSyntaxException;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.Map;
import javax.annotation.Nullable;
import lombok.extern.slf4j.Slf4j;
import net.runelite.api.coords.WorldPoint;

/**
 * Works out which named area of the world a position is in, and which surface entrance leads
 * there, from data extracted out of the game cache.
 * <p>
 * The world map draws each detached area, dungeons included, in its own corner of the world
 * grid, and RuneLite only draws a world map point when the map currently on screen actually
 * covers it. So a member standing in a dungeon appears correctly once you pan to that
 * dungeon's map, and is simply absent from the overworld. This class supplies the missing
 * half: where on the overworld to draw a marker saying "they are below here".
 * <p>
 * The backing resource is generated by {@code tools/mapdump}, which reads the world map
 * definitions and the map's own intermap links straight out of the game cache. Nothing here
 * is hand-measured, and regenerating it after a game update is a single command.
 */
@Slf4j
public final class MapAreas
{
	private static final String RESOURCE = "/com/groupironmencompanion/map-areas.json";

	/**
	 * The standard underground band. Areas at or above this are laid out directly beneath
	 * their surface counterpart, offset by exactly this much, which is what makes the
	 * projection fallback below work when the cache offers no explicit link.
	 */
	private static final int UNDERGROUND_Y = 6400;

	/** How near a link outside every known area has to be before it is trusted, in tiles. */
	private static final int LOOSE_LINK_RADIUS = 64;

	/**
	 * How far a projected position may be from a real entrance and still snap to it.
	 * <p>
	 * Deliberately tight. A generous radius mislabels: the Barrows tunnels project to within
	 * 85 tiles of the Shade Catacombs entrance, which is a different dungeon entirely. Keeping
	 * this small means an unrecognised area falls back to the bare projection rather than
	 * confidently pointing at the wrong door. Holding the marker still as a member walks
	 * around underground is {@code GroupMapMarkers}' job, not this one's.
	 */
	private static final int ENTRANCE_SNAP_RADIUS = 64;

	/**
	 * Places in the underground band that are not under anything, keyed by map square.
	 * <p>
	 * The projection below assumes an area sits 6400 tiles directly beneath the surface it
	 * belongs to. That holds for the Barrows tunnels and most caves. It does not hold for a
	 * detached pocket with no world map of its own: subtract 6400 from Guardians of the Rift
	 * and the result is the open sea east of Morytania, which is what the marker used to
	 * claim.
	 * <p>
	 * Nothing in the cache separates the two cases. Both have no area, no intermap link, and
	 * no entrance within snapping distance, and both project onto squares the overworld draws,
	 * because the overworld draws sea. The gap in distance-to-nearest-entrance is 85 tiles
	 * against 125, with a smooth spread of a thousand other squares across that range, so
	 * there is no threshold to find.
	 * <p>
	 * So this is a short, deliberately hand-entered list, and the only positional data in the
	 * plugin that is not generated. Entries carry a name and no position, which is the point:
	 * the member is named rather than pinned. They are not lost by it, because the world map
	 * draws these areas at their real coordinates, far north of the overworld where the
	 * detached maps are laid out, and their own marker is already there.
	 * <p>
	 * To add one: stand in the area, take the coordinates, and pack them the way
	 * {@link #squareOf} does.
	 */
	private static final Map<Integer, Detached> DETACHED_AREAS = detachedAreas();

	private static Map<Integer, Detached> detachedAreas()
	{
		Map<Integer, Detached> detached = new HashMap<>();

		// Guardians of the Rift. The transport in and out of the arena is at (3615, 9469),
		// which is square (56, 147) at an offset of 31 east and 61 north within it. Sitting
		// three tiles from that square's northern edge means the arena necessarily continues
		// into (56, 148), and being mid-square on the x axis means it may reach either side,
		// so the box is a square wider in each direction than the one observed point proves.
		//
		// Over-covering is close to free here. This map is only consulted when no real area
		// claims the square, and the box is hemmed in by areas that do: Kharidian Desert
		// Underground to the west, Mos Le'Harmless Cave to the east. The cost of guessing too
		// small is that the bug comes back for part of the arena; too large, and some other
		// unmapped pocket borrows the wrong name while still losing the pin it should not have
		// had.
		// You reach the arena through the portal in the Wizards' Tower basement, and the
		// basement itself from the ladder in the tower. That ladder is the surface end, and it
		// is not a guess: the cache's own intermap links pair (3103, 9576) with (3104, 3162),
		// so the coordinate comes from the same data everything else here does.
		addBox(detached, 55, 57, 147, 148,
			new Detached("Guardians of the Rift", new WorldPoint(3104, 3162, 0)));

		return detached;
	}

	private static void addBox(Map<Integer, Detached> into, int squareX0, int squareX1,
		int squareY0, int squareY1, Detached area)
	{
		for (int x = squareX0; x <= squareX1; x++)
		{
			for (int y = squareY0; y <= squareY1; y++)
			{
				into.put(x * 256 + y, area);
			}
		}
	}

	/**
	 * A detached area, and optionally where on the surface you travel to it from.
	 * <p>
	 * The entrance is separate from the name because the two are known independently. Naming
	 * an area needs only the observation that a member is in it; pinning one to the surface
	 * needs the travel point, which is not in any data the plugin can read - the cache's
	 * object placements are encrypted, and the area has no world map whose links could be
	 * followed. Until that coordinate is known for an area, it is named and left unpinned.
	 */
	private static final class Detached
	{
		private final String name;
		private final WorldPoint surfaceEntrance;

		Detached(String name, @Nullable WorldPoint surfaceEntrance)
		{
			this.name = name;
			this.surfaceEntrance = surfaceEntrance;
		}
	}

	private static volatile MapAreas instance;

	private final Map<Integer, Area> bySquare;
	private final Link[] looseLinks;
	private final Entrance[] entrances;

	private MapAreas(Resource resource)
	{
		bySquare = new HashMap<>();
		if (resource.areas != null)
		{
			for (Area area : resource.areas)
			{
				if (area.squares == null)
				{
					continue;
				}
				for (int square : area.squares)
				{
					bySquare.put(square, area);
				}
			}
		}
		looseLinks = resource.looseLinks == null ? new Link[0] : resource.looseLinks;
		entrances = resource.entrances == null ? new Entrance[0] : resource.entrances;
	}

	public static MapAreas get(Gson gson)
	{
		MapAreas local = instance;
		if (local == null)
		{
			synchronized (MapAreas.class)
			{
				local = instance;
				if (local == null)
				{
					instance = local = load(gson);
				}
			}
		}
		return local;
	}

	private static MapAreas load(Gson gson)
	{
		try (InputStream in = MapAreas.class.getResourceAsStream(RESOURCE))
		{
			if (in == null)
			{
				log.warn("Group Ironmen Tracker In-Game Companion: {} is missing from the plugin jar", RESOURCE);
				return new MapAreas(new Resource());
			}
			Resource resource = gson.fromJson(
				new InputStreamReader(in, StandardCharsets.UTF_8), Resource.class);
			return new MapAreas(resource == null ? new Resource() : resource);
		}
		catch (IOException | JsonSyntaxException e)
		{
			log.warn("Group Ironmen Tracker In-Game Companion: could not read {}", RESOURCE, e);
			return new MapAreas(new Resource());
		}
	}

	/** Squares are 64x64 tiles, packed the same way the generator packs them. */
	private static int squareOf(int x, int y)
	{
		return (x / 64) * 256 + (y / 64);
	}

	/**
	 * Describes where a position is. Returns null when the position is on the overworld map,
	 * because a member standing there is already drawn where they are.
	 */
	@Nullable
	public Located locate(WorldPoint point)
	{
		if (point == null)
		{
			return null;
		}

		int square = squareOf(point.getX(), point.getY());

		Area area = bySquare.get(square);
		if (area == null && point.getY() < UNDERGROUND_Y)
		{
			// Not in any detached area and not in the underground band: this is the overworld.
			return null;
		}

		if (area == null)
		{
			Detached detached = DETACHED_AREAS.get(square);
			if (detached != null)
			{
				// Somewhere the world map has no map for, and nothing above it to project to.
				// Pinned at its travel point when that is known, named and left unpinned when
				// it is not; either way the invented position is gone. See DETACHED_AREAS.
				return new Located(detached.name, detached.surfaceEntrance, null);
			}
		}

		String areaName = area == null ? null : area.name;

		// 1. The area's own exits, as the world map itself defines them.
		if (area != null && area.exits != null && area.exits.length > 0)
		{
			Link best = nearest(area.exits, point, Integer.MAX_VALUE);
			if (best != null)
			{
				return new Located(areaName, new WorldPoint(best.ex, best.ey, 0), best.name);
			}
		}

		// 2. A link the cache places outside every named area, if one is genuinely close.
		Link loose = nearest(looseLinks, point, LOOSE_LINK_RADIUS);
		if (loose != null)
		{
			return new Located(areaName, new WorldPoint(loose.ex, loose.ey, 0), loose.name);
		}

		// 3. Project straight up out of the underground band, then snap to the nearest real
		// entrance. Areas in this band sit directly below the surface they belong to, so the
		// projection lands near the right doorway, but on its own it would track the member's
		// every step. Snapping anchors the marker to the entrance nearest them instead.
		if (point.getY() >= UNDERGROUND_Y)
		{
			WorldPoint projected = new WorldPoint(point.getX(), point.getY() - UNDERGROUND_Y, 0);

			Entrance snapped = nearestEntrance(projected);
			if (snapped != null)
			{
				return new Located(areaName, new WorldPoint(snapped.x, snapped.y, 0), snapped.name);
			}

			// Nothing known nearby; the bare projection still beats no marker at all.
			return new Located(areaName, projected, null);
		}

		// Known area, no way to place it on the surface. The name alone is still worth having.
		return new Located(areaName, null, null);
	}

	/** The curated surface entrance nearest a point, within the snap radius. */
	@Nullable
	private Entrance nearestEntrance(WorldPoint point)
	{
		Entrance best = null;
		long bestDistance = Long.MAX_VALUE;
		long limit = (long) ENTRANCE_SNAP_RADIUS * ENTRANCE_SNAP_RADIUS;

		for (Entrance entrance : entrances)
		{
			long dx = entrance.x - point.getX();
			long dy = entrance.y - point.getY();
			long distance = dx * dx + dy * dy;
			if (distance < bestDistance)
			{
				bestDistance = distance;
				best = entrance;
			}
		}

		return bestDistance <= limit ? best : null;
	}

	@Nullable
	private static Link nearest(Link[] links, WorldPoint point, int maxDistance)
	{
		Link best = null;
		long bestDistance = Long.MAX_VALUE;
		long limit = (long) maxDistance * maxDistance;

		for (Link link : links)
		{
			long dx = link.x - point.getX();
			long dy = link.y - point.getY();
			long distance = dx * dx + dy * dy;
			if (distance < bestDistance)
			{
				bestDistance = distance;
				best = link;
			}
		}

		return bestDistance <= limit ? best : null;
	}

	/** Where a member is, and how to find them from the overworld. */
	public static final class Located
	{
		private final String areaName;
		private final WorldPoint entrance;
		private final String entranceName;

		Located(String areaName, WorldPoint entrance, String entranceName)
		{
			this.areaName = areaName;
			this.entrance = entrance;
			this.entranceName = entranceName;
		}

		/** The game's name for the map they are on, e.g. "Taverley Underground". */
		@Nullable
		public String getAreaName()
		{
			return areaName;
		}

		/** The surface point that leads to them, or null when nothing leads there. */
		@Nullable
		public WorldPoint getEntrance()
		{
			return entrance;
		}

		/** The entrance's own name, e.g. "Taverley Dungeon", when one is known. */
		@Nullable
		public String getEntranceName()
		{
			return entranceName == null || entranceName.isEmpty() ? null : entranceName;
		}

		/** The best label available for this location. */
		public String describe()
		{
			if (getEntranceName() != null)
			{
				return entranceName;
			}
			if (areaName != null)
			{
				return areaName;
			}
			return "underground";
		}
	}

	// ------------------------------------------------------------------
	// Resource shape, bound by Gson from concrete classes and plain arrays
	// ------------------------------------------------------------------

	private static final class Resource
	{
		private Area[] areas;
		private Link[] looseLinks;
		private Entrance[] entrances;
	}

	/** A named surface entrance, from RuneLite's curated dungeon entrance list. */
	private static final class Entrance
	{
		private int x;
		private int y;
		private String name;
	}

	private static final class Area
	{
		private String name;
		private int[] squares;
		private Link[] exits;
	}

	private static final class Link
	{
		private int x;
		private int y;
		private int ex;
		private int ey;
		private String name;
	}
}
